-- Mesmo schema nos dois bancos. A replicação lógica não copia DDL:
-- toda mudança de estrutura precisa ser feita na origem E no destino.

DROP TABLE IF EXISTS itens_pedido, pedidos, produtos, clientes, sonda_latencia, avaliacoes CASCADE;

CREATE TABLE clientes (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           text NOT NULL,
    email          text NOT NULL,
    cidade         text,
    criado_em      timestamptz NOT NULL DEFAULT now(),
    atualizado_em  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE produtos (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           text NOT NULL,
    categoria      text NOT NULL,
    preco          numeric(10,2) NOT NULL,
    estoque        integer NOT NULL,
    atualizado_em  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE pedidos (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     bigint NOT NULL REFERENCES clientes (id),
    status         text NOT NULL,          -- novo, pago, enviado, entregue, cancelado
    total          numeric(12,2) NOT NULL,
    criado_em      timestamptz NOT NULL DEFAULT now(),
    atualizado_em  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE itens_pedido (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       bigint NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    produto_id      bigint NOT NULL REFERENCES produtos (id),
    quantidade      integer NOT NULL,
    preco_unitario  numeric(10,2) NOT NULL
);

-- Sonda: uma linha inserida na origem e esperada no destino mede o atraso
-- do começo ao fim. Como o destino aplica as mudanças na ordem do commit,
-- quando a sonda chega, tudo o que foi gravado antes dela também chegou.
CREATE TABLE sonda_latencia (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enviado_em  timestamptz NOT NULL DEFAULT clock_timestamp()
);
